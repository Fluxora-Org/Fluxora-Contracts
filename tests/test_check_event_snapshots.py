def test_main_returns_2_when_events_source_is_missing(tmp_path, capsys):
    result = snapshots.main(
        ["--events", str(tmp_path / "absent.rs"), "--fixtures", str(tmp_path)]
    )

    assert result == 2
    assert "events source not found" in capsys.readouterr().err


def test_main_returns_2_when_no_event_structs_are_parsed(tmp_path, capsys):
    source = tmp_path / "events.rs"
    source.write_text("pub struct NotAnEvent { pub x: u64 }\n")

    result = snapshots.main(["--events", str(source), "--fixtures", str(tmp_path)])

    assert result == 2
    assert "no #[contractevent] structs parsed" in capsys.readouterr().err


def test_main_update_then_check_round_trips(tmp_path):
    source = tmp_path / "events.rs"
    source.write_text(SOURCE)

    assert snapshots.main(["--events", str(source), "--fixtures", str(tmp_path)]) == 1
    assert (
        snapshots.main(["--events", str(source), "--fixtures", str(tmp_path), "--update"])
        == 0
    )
    assert snapshots.main(["--events", str(source), "--fixtures", str(tmp_path)]) == 0


def test_main_fails_when_a_new_event_is_added_without_a_fixture(tmp_path, capsys):
    fixtures = tmp_path / "fixtures"
    snapshots.update(snapshots.parse_events(SOURCE), fixtures)

    new_event = (
        "\n/// Shipped without a fixture.\n"
        "#[contractevent]\n"
        "pub struct GammaEvent {\n"
        "    #[topic]\n"
        "    pub stream_id: u64,\n"
        "}\n"
    )
    source = tmp_path / "events.rs"
    source.write_text(SOURCE + new_event)

    result = snapshots.main(["--events", str(source), "--fixtures", str(fixtures)])

    assert result == 1
    assert "gamma_event.json: fixture missing" in capsys.readouterr().out


# ---------------------------------------------------------------------------
# The repository as committed — the CI-enforced guarantee
# ---------------------------------------------------------------------------


def test_committed_fixtures_cover_every_emitted_event_type():
    schemas = snapshots.parse_events(snapshots.EVENTS_RS.read_text(encoding="utf-8"))
    topics = [schema.topic for schema in schemas]

    # No two event structs may generate the same namespace symbol.
    assert len(topics) == len(set(topics))
    assert set(topics) == EXPECTED_TOPICS

    # One fixture per event, no orphans, exact payload match.
    fixture_stems = {path.stem for path in snapshots.FIXTURES_DIR.glob("*.json")}
    assert fixture_stems == EXPECTED_TOPICS
    assert snapshots.main([]) == 0


def test_committed_fixtures_pin_the_documented_topic_arity():
    schemas = {
        schema.topic: schema
        for schema in snapshots.parse_events(
            snapshots.EVENTS_RS.read_text(encoding="utf-8")
        )
    }

    # topic[0] plus every #[topic] field.
    assert len(schemas["stream_created"].topic_fields) == 3
    assert len(schemas["withdrawn"].topic_fields) == 2
    assert len(schemas["recipient_transferred"].topic_fields) == 3
    assert len(schemas["delegate_granted"].topic_fields) == 3
    assert len(schemas["ttl_extended"].topic_fields) == 1
    assert len(schemas["halt_operator_set"].topic_fields) == 1
